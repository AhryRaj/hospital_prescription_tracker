-- 1. Select Database
USE hospital_db;

-- 2. Create Tables if they do not exist
CREATE TABLE IF NOT EXISTS Drug (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  category VARCHAR(255) NOT NULL,
  size_amount DOUBLE NOT NULL,
  size_unit VARCHAR(50) NOT NULL,
  unit_price DOUBLE NOT NULL,
  frequency INT NOT NULL DEFAULT 3,
  days INT NOT NULL DEFAULT 5
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS Prescription (
  id INT AUTO_INCREMENT PRIMARY KEY,
  date DATE NOT NULL,
  patient_id VARCHAR(255) NOT NULL,
  drug_id INT NOT NULL,
  dose DOUBLE NOT NULL,
  total_qty DOUBLE NOT NULL,
  total_cost DOUBLE NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_prescription_drug FOREIGN KEY (drug_id) REFERENCES Drug(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

